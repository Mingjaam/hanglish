using System.Text.Json;
using Hanglish.Core;

/// <summary>
/// Records what the engine shows after every key of the website demo, so the site's motion
/// graphic replays real behavior instead of a hand-made imitation. Keys: "_" Space, "|" Return,
/// "!" flip; anything else is typed as is.
/// </summary>
static class Frames
{
    public static readonly (string Caption, string Keys)[] Scenes =
    {
        ("한글은 그냥 치면 한글", "dkssudgktpdy."),
        ("영어도 한/영 키 없이", "|hello_world."),
        ("섞어 써도 알아서", "|githubdptj_zhemfmf_qkedkTdj."),
        ("이름도 한글로", "|rlaalswo_dlqslek."),
        ("애매하면 뒤 단어를 보고 고쳐요", "|so_good."),
        ("앞 문맥까지 함께 고쳐요", "|dhsmf_to_do_list."),
        ("틀리면 오른쪽 Ctrl 한 번", "|go_!"),
    };

    public static void Write(Decider decider, string path)
    {
        var engine = new Engine(decider, new CorrectionStore(null));
        var field = "";
        var scenes = new List<object>();
        foreach (var (caption, keys) in Scenes)
        {
            var steps = new List<object>();
            foreach (var k in keys)
            {
                (KeyAction Action, string? Passed) r = k switch
                {
                    '_' => (engine.Boundary(" "), " "),
                    '|' => (engine.Boundary(null), "\n"),
                    '!' => (engine.Flip(), null),
                    _ when char.IsAsciiLetter(k) => (engine.Letter(k), k.ToString()),
                    _ => (engine.Boundary(k.ToString()), k.ToString()),
                };
                field = field[..Math.Max(0, field.Length - r.Action.Backspaces)] + r.Action.Text;
                if ((!r.Action.Swallow || r.Action.Replay) && r.Passed is not null) field += r.Passed;
                var guess = engine.Guess();
                steps.Add(new
                {
                    key = k switch { '_' => "Space", '|' => "Enter", '!' => "Ctrl", _ => k.ToString() },
                    field,
                    bubble = guess is null ? null : new { text = guess.Text, korean = guess.Korean, alt = guess.Alternative },
                });
            }
            scenes.Add(new { caption, steps });
        }
        var json = JsonSerializer.Serialize(scenes, new JsonSerializerOptions
        {
            Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        });
        File.WriteAllText(path, "// Generated by: Hanglish.Eval --frames site/frames.js (real engine output)\nwindow.HANGLISH_FRAMES = " + json + ";\n");
    }
}
